#!/usr/bin/env python3
"""Write INVENTORY.md for the linked real data: per file, per dataset (shape, dtype,
chunks, filters with their options, frame count), plus sha256 from MANIFEST.sha256.

Usage: python3 tools/data_inventory.py <data/real dir>
Read-only on the data. Needs h5py (the shared environment).
"""
import os
import sys

import h5py


def filters_of(ds):
    out = []
    pl = ds.id.get_create_plist()
    for i in range(pl.get_nfilters()):
        fid, flags, opts, name = pl.get_filter(i)
        out.append("%d%s%s" % (fid, ("(%s)" % name.decode() if name else ""),
                               " opts=%s" % (list(opts),) if opts else ""))
    return ", ".join(out) or "none"


def describe(path):
    rows = []
    try:
        with h5py.File(path, "r") as f:
            def visit(name, obj):
                if isinstance(obj, h5py.Dataset) and obj.ndim >= 2 and obj.size > 1000:
                    rows.append((name, obj.shape, str(obj.dtype), obj.chunks, filters_of(obj)))
            f.visititems(visit)
    except OSError as e:
        return [("(not readable as HDF5: %s)" % e, None, "", None, "")]
    return rows


def main():
    d = sys.argv[1]
    sums = {}
    with open(os.path.join(d, "MANIFEST.sha256")) as fh:
        for line in fh:
            h, n = line.split(None, 1)
            sums[n.strip()] = h
    lines = ["# Real data inventory", "",
             "Generated by tools/data_inventory.py. The files are read-only symlinks;",
             "MANIFEST.sha256 holds the checksums (`dev-root check` verifies them).", ""]
    for n in sorted(sums):
        p = os.path.join(d, n)
        lines.append("## %s" % n)
        lines.append("")
        lines.append("- sha256: `%s`" % sums[n])
        lines.append("- size: %d bytes (%s)" % (os.path.getsize(p), os.path.realpath(p)))
        if n.endswith((".h5", ".hdf5", ".nxs")):
            rows = describe(p)
            lines.append("")
            lines.append("| dataset | shape | dtype | chunks | frames | filters |")
            lines.append("|---|---|---|---|---|---|")
            for name, shape, dt, ch, fl in rows[:40]:
                lines.append("| %s | %s | %s | %s | %s | %s |" % (
                    name, shape, dt, ch, shape[0] if shape and len(shape) == 3 else "-", fl))
        lines.append("")
    open(os.path.join(d, "INVENTORY.md"), "w").write("\n".join(lines))
    print("wrote", os.path.join(d, "INVENTORY.md"))


main()
