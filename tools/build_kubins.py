#!/usr/bin/env python3
"""Compile each slabitz kernel, on its own, to one cubin for a single CUDA arch.

This is the portable-cards path: the default build (tools/build_all.py) uses the
local nvcc, which can't target Kepler sm_35. For sm_35, run this with the CUDA
11.8 nvcc (or any toolkit that still supports the arch) over the .cu files that
already exist: the Slang kernels' build/<sub>/<Ker>.cu (written by slangc) and the
(all kernels are Slang now).

The ROADMAP warns against a merged fatbin for the Slang kernels (include-guarded
DS headers: a merged module compiles the shader bodies once under the first
kernel's macro state), so we keep one cubin per kernel and load each as its own
CUDA module (sbz_cuda.c does this). Keep the same subdir/cubin names as
tools/gen_kernel_table.py so sbz_cuda.c finds them.

  pixi run -e kepler build-sm35          # = the NVRTC line below, into build/sm_35
  python3 tools/build_kubins.py --arch sm_35 --out build/sm_35 --nvrtc <11.8>/lib/libnvrtc.so
  python3 tools/build_kubins.py --arch sm_61 --out build/sm_61 --nvcc nvcc

--nvrtc compiles in-process with NVRTC (no host compiler; nvcc 11.8 rejects
gcc > 11, NVRTC does not care). Without it, --nvcc is used.
"""
import argparse
import os
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from build_all import KERNEL_MAP  # noqa: E402

SLANGINC = str(ROOT / "third_party" / "slang" / "include")
SHIM = "slang_cuda_prevolta.h"     # tools/: pre-Volta wave-mask semantics, no-op on Volta+


def run(cmd):
    print("  +", " ".join(str(c) for c in cmd), flush=True)
    subprocess.run([str(c) for c in cmd], check=True)


# Slang kernels are generated by slangc with C++17 semantics (constexpr-if etc.),
# so pin the standard (nvcc 11.x defaults are older).
CXX = ["--std=c++17", "-Wno-deprecated-gpu-targets"]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--arch", default="sm_35")
    ap.add_argument("--out", default="build")
    ap.add_argument("--nvcc", default=os.environ.get("NVCC", "nvcc"))
    ap.add_argument("--nvrtc", default=None,
                    help="path to libnvrtc.so: compile with NVRTC instead of nvcc")
    ap.add_argument("--no-shim", action="store_true",
                    help="do not pre-include tools/%s in the Slang kernels (A/B tests)" % SHIM)
    a = ap.parse_args(argv)
    out = pathlib.Path(a.out)

    if a.nvrtc:
        from build_cuda_fatbin import Nvrtc
        nv = Nvrtc(a.nvrtc)
        nv.options = nv.options + ["-I" + str(HERE), "-I" + SLANGINC]
        print("NVRTC %d.%d: %s" % (nv.version + (a.nvrtc,)))

    def compile_cubin(cu, dst, extra, shim=False):
        shim = shim and not a.no_shim
        if a.nvrtc:
            print("  + nvrtc -arch=%s%s %s -> %s" % (a.arch, " +shim" if shim else "", cu, dst),
                  flush=True)
            src = pathlib.Path(cu).read_text()
            if shim:
                src = '#include "%s"\n' % SHIM + src
            data, _ = nv.compile(src, [], a.arch)
            pathlib.Path(dst).write_bytes(data)
        else:
            if shim:
                extra = extra + ["-I", str(HERE), "-I", SLANGINC, "-include", SHIM]
            run([a.nvcc, "-arch=" + a.arch, "-cubin"] + extra + CXX + [str(cu), "-o", str(dst)])

    # Slang kernels: .cu already written by slangc in build_all's subdirs.
    for ker, sub, cubin in KERNEL_MAP:
        cu = ROOT / "build" / sub / ("%s.cu" % ker)
        if not cu.exists():
            raise SystemExit("missing %s (run tools/build_all.py first)" % cu)
        d = out / sub
        d.mkdir(parents=True, exist_ok=True)
        compile_cubin(cu, d / cubin, [], shim=True)

    # the kernel set's build ID (tools/gen_kernel_table.py): the library refuses
    # a kernel directory without the ID it was generated with
    kid = ROOT / "build" / "sbz_kernels.id"
    if not kid.exists():
        raise SystemExit("missing %s (run tools/build_all.py first)" % kid)
    (out / "sbz_kernels.id").write_bytes(kid.read_bytes())
    print("wrote %d sm_%s cubins to %s (kernels id %s)"
          % (len(KERNEL_MAP), a.arch[3:], out, kid.read_text().strip()))


if __name__ == "__main__":
    sys.exit(main())
