#!/usr/bin/env python3
"""Generate src/sbz_kernels_gen.h from the slangc reflection JSON of each kernel.

The C stage driver (src/sbz_chain.c) binds device buffers to kernel parameters BY
NAME and checks every launch against this table: each parameter bound exactly once,
buffer element size == the kernel's element size, scalar vs buffer kind. This turns
an argument-packing mistake (the classic way to corrupt memory silently through
cuLaunchKernel, which has no type information) into an error at the first launch.

The table also carries each kernel's thread-group size (numthreads), so the C side
never hard-codes the TG sizes that depend on DS preprocessor state.

Input: build/<sub>/<Kernel>.json written by `slangc ... -reflection-json`.
Usage: tools/gen_kernel_table.py [--build build] [--out src/sbz_kernels_gen.h]
       (tools/build_all.py calls this after compiling every kernel)
"""
import argparse
import hashlib
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from build_all import KERNEL_MAP  # noqa: E402

# Everything that shapes the compiled kernels. Their content (not mtimes or
# absolute paths, so the ID is the same in every clone) goes into
# SBZ_KERNELS_ID, together with the launch table itself. The library refuses a
# kernel directory whose sbz_kernels.id differs: a stale kernel set otherwise
# loads silently, and a changed argument list crashes the launch.
ID_SOURCES = ["kernels/*.slang", "kernels/lib/*", "third_party/directstorage_zstdgpu/**/*",
              "tools/transform_ds_for_slang.py", "tools/slang_compat.h",
              "tools/slang_cuda_prevolta.h", "tools/fetch_slangc.sh"]
ID_FILE = "sbz_kernels.id"


def kernels_id(table_text):
    """16 hex digits: SHA-256 over the ID_SOURCES files (sorted relative
    paths and contents) and the generated launch table."""
    h = hashlib.sha256()
    files = sorted({p for pat in ID_SOURCES for p in ROOT.glob(pat) if p.is_file()})
    if not files:
        raise SystemExit("gen_kernel_table: no kernel sources found under %s" % ROOT)
    for p in files:
        h.update(str(p.relative_to(ROOT)).encode() + b"\0")
        h.update(p.read_bytes() + b"\0")
    h.update(table_text.encode())
    return h.hexdigest()[:16]

SCALAR_SIZE = {"uint8": 1, "int8": 1, "uint16": 2, "int16": 2, "uint32": 4, "int32": 4,
               "float32": 4, "uint64": 8, "int64": 8, "float64": 8}

# param kinds (must match sbz_chain.h SBZ_KP_*)
KP_SBUF, KP_BAB, KP_U32 = 0, 1, 2


def type_size(t):
    k = t["kind"]
    if k == "scalar":
        return SCALAR_SIZE[t["scalarType"]]
    if k == "struct":
        for s in t.get("sizes", []):
            if s.get("kind") == "uniform":
                return s["value"]
        return sum(type_size(f["type"]) for f in t["fields"])
    if k == "vector":
        return t["elementCount"] * type_size(t["elementType"])
    raise ValueError("unhandled type kind %r" % k)


def params_of(js):
    ep = js["entryPoints"][0]
    tg = ep["threadGroupSize"]
    out = []
    for p in ep["parameters"]:
        if p.get("semanticName"):
            continue  # SV_* system values are not launch arguments
        t = p["type"]
        if t["kind"] == "resource":
            shape = t["baseShape"]
            rw = 1 if t.get("access") == "readWrite" else 0
            if shape == "structuredBuffer":
                out.append((p["name"], KP_SBUF, type_size(t["resultType"]), rw))
            elif shape == "byteAddressBuffer":
                out.append((p["name"], KP_BAB, 1, rw))
            else:
                raise ValueError("unhandled resource shape %r (%s)" % (shape, p["name"]))
        elif t["kind"] == "scalar" and t["scalarType"] in ("uint32", "int32"):
            out.append((p["name"], KP_U32, 4, 0))
        else:
            raise ValueError("unhandled param %s kind %r" % (p["name"], t["kind"]))
    return tg, out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default=str(ROOT / "build"))
    ap.add_argument("--out", default=str(ROOT / "src" / "sbz_kernels_gen.h"))
    a = ap.parse_args(argv)
    build = pathlib.Path(a.build)

    lines = [
        "/* AUTO-GENERATED by tools/gen_kernel_table.py from slangc -reflection-json.",
        " * DO NOT EDIT. Regenerate with tools/build_all.py. */",
        "#ifndef SBZ_KERNELS_GEN_H",
        "#define SBZ_KERNELS_GEN_H",
        "",
        "enum sbz_kernel_id {",
    ]
    for ker, _sub, _cubin in KERNEL_MAP:
        lines.append("    SBZK_%s," % ker)
    lines += ["    SBZK_COUNT", "};", ""]

    infos = []
    for ker, sub, cubin in KERNEL_MAP:
        jp = build / sub / ("%s.json" % ker)
        js = json.loads(jp.read_text())
        tg, ps = params_of(js)
        if tg[1] != 1 or tg[2] != 1:
            raise SystemExit("%s: only 1-D thread groups supported, got %r" % (ker, tg))
        lines.append("static const sbz_kparam sbz_kparams_%s[] = {" % ker)
        for name, kind, esz, rw in ps:
            lines.append('    { "%s", %d, %d, %d },' % (name, kind, esz, rw))
        lines.append("};")
        infos.append('    { "%s", "%s/%s", "main_0", %d, %d, sbz_kparams_%s },'
                     % (ker, sub, cubin, tg[0], len(ps), ker))
    lines += ["", "static const sbz_kinfo sbz_kernel_table[SBZK_COUNT] = {"] + infos + ["};", ""]
    kid = kernels_id("\n".join(lines))
    lines += ["/* Build ID of the kernel set this library was generated with; a kernel",
              " * directory must carry the same ID in its %s file. */" % ID_FILE,
              '#define SBZ_KERNELS_ID "%s"' % kid, "",
              "#endif /* SBZ_KERNELS_GEN_H */", ""]
    pathlib.Path(a.out).write_text("\n".join(lines))
    (build / ID_FILE).write_text(kid + "\n")
    print("wrote", a.out, "and", build / ID_FILE, "(kernels id %s)" % kid)
    return 0


if __name__ == "__main__":
    sys.exit(main())
